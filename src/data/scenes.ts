import { BASE } from "../lib/asset";

export type Depth = 0 | 1 | 2 | 3 | 4;

export interface SceneMeta {
  /** id ของ <section> ใช้เป็น anchor ของ scene indicator */
  id: string;
  number: string;
  /** ชื่อฉากสำหรับ aria-label ของ scene indicator (ใช้หัวข้อฉากจาก content.md) */
  title: string;
  depth: Depth;
  bg: string;
  fg?: string;
}

export interface CaptionedText {
  title: string;
  body: string;
}

export interface FishGroup {
  id: string;
  title: string;
  points: string[];
  examples: string;
  /** หมายเหตุจาก content.md (เช่น กลุ่ม 8 ไม่มีจุดเด่น) — ไม่แสดงบนหน้าเว็บ */
  note?: string;
  /** ภาพประกอบ SVG เดิม — ใช้เป็น fallback เมื่อภาพจริงโหลดไม่ได้ */
  image: string;
  alt: string;
  photo: FishImage;
}

export interface FishImage {
  src: string;
  /** ชื่อปลาภาษาไทยตาม content.md */
  alt: string;
}

export interface Labeled {
  id: string;
  text: string;
  en: string;
}

export interface PlantType {
  id: "marginal" | "emerged" | "submerged" | "floating";
  title: string;
  en: string;
  body: string;
  /** ตัวอย่างชนิด — ชื่อวิทยาศาสตร์แยกไว้เพื่อแสดงตัวเอียง */
  examples: { name: string; scientific?: string }[];
}

export interface TankZone {
  id: "back" | "middle" | "front";
  title: string;
  body: string;
  examplesLead: string;
  examples: string;
}

export interface Factor {
  id: "light" | "turbidity" | "ph" | "nitrogen" | "phosphorus";
  title: string;
  lines: string[];
  iconAlt: string;
}

